// ─────────────────────────────────────────────────────────────
// SMART MATCHING — Thuật toán 40/40/20 từ SmartMatchingHandler.cs
// ─────────────────────────────────────────────────────────────
export function runSmartMatching(
  requiredCapacityKwh: number,
  targetVoltageV: number,
  maxBudgetVnd: number,
  preferredChemistry?: string
): MatchingResult[] {
  const results: MatchingResult[] = [];

  for (const listing of MOCK_LISTINGS) {
    if (!listing.isActive || listing.isSold) continue;
    if (listing.askingPriceVnd > maxBudgetVnd) continue;
    if (preferredChemistry && preferredChemistry !== 'ALL' && listing.batteryPack.chemistry !== preferredChemistry) continue;

    const pack = listing.batteryPack;

    // Thuật toán SmartMatchingHandler.cs: Trọng số 40 / 40 / 20
    const capacityScore = Math.min(100, (pack.currentCapacityKwh / requiredCapacityKwh) * 100);
    const sohScore = pack.currentSohPercent;
    const voltageScore = Math.abs(pack.nominalVoltageV - targetVoltageV) < 50 ? 100 : 70;
    const matchScore = (capacityScore * 0.4) + (sohScore * 0.4) + (voltageScore * 0.2);

    // EstimatedBessPriceVnd = AskingPrice + 15.000.000 (chi phí lắp đặt ước tính)
    const estimatedBessPriceVnd = listing.askingPriceVnd + 15000000;

    const reasonParts: string[] = [];
    reasonParts.push(`Dung lượng: ${pack.currentCapacityKwh.toFixed(1)} kWh (yêu cầu ${requiredCapacityKwh} kWh)`);
    reasonParts.push(`SOH: ${pack.currentSohPercent}%`);
    reasonParts.push(`Điện áp: ${pack.nominalVoltageV}V`);

    results.push({
      listing,
      matchScorePercent: Math.round(matchScore * 10) / 10,
      matchReason: reasonParts.join(' • '),
      estimatedBessPriceVnd,
    });
  }

  // Sắp xếp giảm dần theo score, lấy top 10 (BR-009)
  return results.sort((a, b) => b.matchScorePercent - a.matchScorePercent).slice(0, 10);
}
